function trs(s) {
  const m = s.match(/^(\s*)([\s\S]*?)(\s*)$/),
    c = m[2];
  if (!c) return s;
  let r = EN[c];
  if (r == null)
    for (const [x, t] of RX) {
      const k = c.match(x);
      if (k) {
        r = t.replace(/\$(\d)/g, (_, i) => trs(k[i]));
        break;
      }
    }
  return r == null ? s : m[1] + r + m[3];
}
