function tx(n) {
  if (n.parentElement?.closest('[translate="no"]')) return;
  let s = M.get(n),
    v = n.nodeValue;
  if (!s || (v !== s.o && v !== s.t)) s = { o: v };
  s.t = lang == 'en' ? trs(s.o) : s.o;
  M.set(n, s);
  if (v !== s.t) n.nodeValue = s.t;
}
function walk(r) {
  if (r.nodeType == 3) {
    if (!SK.test(r.parentNode?.tagName)) tx(r);
    return;
  }
  if (r.nodeType != 1 || SK.test(r.tagName)) return;
  for (const a of AT)
    if (r.hasAttribute(a)) {
      const s = MA.get(r) || {},
        v = r.getAttribute(a),
        e = s[a];
      if (!e || (v !== e.o && v !== e.t)) s[a] = { o: v };
      s[a].t = lang == 'en' ? trs(s[a].o) : s[a].o;
      MA.set(r, s);
      if (v !== s[a].t) r.setAttribute(a, s[a].t);
    }
  r.childNodes.forEach(walk);
}
