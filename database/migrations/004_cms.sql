CREATE TABLE media (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(32) NOT NULL UNIQUE,
 asset_path VARCHAR(190) DEFAULT NULL UNIQUE,
 storage_key VARCHAR(100) DEFAULT NULL UNIQUE,
 original_name VARCHAR(255) NOT NULL,
 mime VARCHAR(60) NOT NULL,
 byte_size INT UNSIGNED NOT NULL,
 width INT UNSIGNED NOT NULL,
 height INT UNSIGNED NOT NULL,
 uploaded_by BIGINT UNSIGNED DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_media_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE products (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(32) NOT NULL UNIQUE,
 legacy_key VARCHAR(80) DEFAULT NULL UNIQUE,
 name_ru VARCHAR(180) NOT NULL,
 name_en VARCHAR(180) NOT NULL,
 taste_ru VARCHAR(180) NOT NULL,
 taste_en VARCHAR(180) NOT NULL,
 note_ru VARCHAR(500) NOT NULL DEFAULT '',
 note_en VARCHAR(500) NOT NULL DEFAULT '',
 color VARCHAR(7) NOT NULL,
 stats_json TEXT NOT NULL,
 stats_en_json TEXT NOT NULL,
 image_media_id BIGINT UNSIGNED DEFAULT NULL,
 cut_media_id BIGINT UNSIGNED DEFAULT NULL,
 is_visible TINYINT(1) NOT NULL DEFAULT 1,
 display_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 deleted_at DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_product_image FOREIGN KEY (image_media_id) REFERENCES media(id),
 CONSTRAINT fk_product_cut FOREIGN KEY (cut_media_id) REFERENCES media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE articles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(32) NOT NULL UNIQUE,
 legacy_key VARCHAR(80) DEFAULT NULL UNIQUE,
 title_ru VARCHAR(240) NOT NULL,
 title_en VARCHAR(240) NOT NULL,
 tag_ru VARCHAR(80) NOT NULL,
 tag_en VARCHAR(80) NOT NULL,
 excerpt_ru VARCHAR(1000) NOT NULL,
 excerpt_en VARCHAR(1000) NOT NULL,
 body_ru MEDIUMTEXT NOT NULL,
 body_en MEDIUMTEXT NOT NULL,
 cover_media_id BIGINT UNSIGNED DEFAULT NULL,
 status ENUM('draft','published') NOT NULL DEFAULT 'draft',
 show_home TINYINT(1) NOT NULL DEFAULT 1,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 published_at DATETIME DEFAULT NULL,
 deleted_at DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_article_cover FOREIGN KEY (cover_media_id) REFERENCES media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE article_images (
 article_id BIGINT UNSIGNED NOT NULL,
 media_id BIGINT UNSIGNED NOT NULL,
 display_order SMALLINT UNSIGNED NOT NULL,
 PRIMARY KEY (article_id,display_order),
 CONSTRAINT fk_article_image_article FOREIGN KEY (article_id) REFERENCES articles(id),
 CONSTRAINT fk_article_image_media FOREIGN KEY (media_id) REFERENCES media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE partner_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 public_id CHAR(32) NOT NULL UNIQUE,
 user_id BIGINT UNSIGNED NOT NULL,
 legacy_key VARCHAR(80) DEFAULT NULL UNIQUE,
 idempotency_key VARCHAR(100) NOT NULL,
 body_hash CHAR(64) NOT NULL,
 name VARCHAR(120) NOT NULL,
 organization VARCHAR(180) NOT NULL,
 email VARCHAR(190) NOT NULL,
 phone VARCHAR(24) NOT NULL,
 status ENUM('new','work','done') NOT NULL DEFAULT 'new',
 consent_accepted_at DATETIME NOT NULL,
 consent_version VARCHAR(80) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 deleted_at DATETIME DEFAULT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_partner_retry (user_id,idempotency_key),
 CONSTRAINT fk_partner_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE site_settings (
 setting_key VARCHAR(80) NOT NULL PRIMARY KEY,
 value_json TEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 updated_by BIGINT UNSIGNED DEFAULT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_setting_editor FOREIGN KEY (updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
